export type PermissionAction = "قراءة" | "إضافة" | "تعديل" | "حذف" | "اعتماد" | "تصدير";

export interface RoleDef {
  id: string;
  name: string;
  description: string;
  color: string;
  scope: "مؤسسي" | "تشغيلي" | "بوابة خارجية";
  risk: "مرتفع" | "متوسط" | "منخفض";
  isSystem?: boolean; // Critical roles cannot be renamed or deleted
  permissions: Record<PermissionModule, PermissionAction[]>;
}

