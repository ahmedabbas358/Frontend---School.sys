const STORAGE_KEY = "darasi_rbac_roles_v2";

export function loadRbacRoles(): RoleDef[] {
  if (typeof window === "undefined") return DEFAULT_RBAC_ROLES;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_RBAC_ROLES;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch (e) {
    console.error("Failed to load RBAC roles:", e);
  }
  return DEFAULT_RBAC_ROLES;
}

export function saveRbacRoles(roles: RoleDef[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(roles));
  } catch (e) {
    console.error("Failed to save RBAC roles:", e);
  }
}

export function resetRbacRoles(): RoleDef[] {
  if (typeof window !== "undefined") {
    localStorage.removeItem(STORAGE_KEY);
  }
  return DEFAULT_RBAC_ROLES;
}
